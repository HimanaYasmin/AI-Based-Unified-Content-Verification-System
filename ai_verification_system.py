import os
import joblib
import numpy as np
import tensorflow as tf
from tensorflow.keras.utils import load_img, img_to_array


# ============================================================
# PROJECT PATHS
# ============================================================

PROJECT_DIR = "/content/drive/MyDrive/AI_Unified_Content_Verification"
MODELS_DIR = os.path.join(PROJECT_DIR, "models")


# ============================================================
# LOAD SAVED MODELS
# ============================================================

fake_news_model = joblib.load(
    os.path.join(MODELS_DIR, "fake_news_logistic_regression.pkl")
)

fake_news_tfidf = joblib.load(
    os.path.join(MODELS_DIR, "fake_news_tfidf.pkl")
)

ai_text_model = joblib.load(
    os.path.join(MODELS_DIR, "ai_text_logistic_regression.pkl")
)

ai_text_tfidf = joblib.load(
    os.path.join(MODELS_DIR, "ai_text_tfidf.pkl")
)

deepfake_model = tf.keras.models.load_model(
    os.path.join(MODELS_DIR, "deepfake_efficientnet_retrained.keras")
)


# ============================================================
# FAKE NEWS DETECTION
# ============================================================

def detect_fake_news(title, text):

    combined_text = str(title) + " " + str(text)

    text_tfidf = fake_news_tfidf.transform([combined_text])

    prediction = fake_news_model.predict(text_tfidf)[0]

    probabilities = fake_news_model.predict_proba(text_tfidf)[0]

    if prediction == 0:
        result = "FAKE NEWS"
        confidence = probabilities[0] * 100
    else:
        result = "REAL NEWS"
        confidence = probabilities[1] * 100

    return result, confidence


# ============================================================
# AI-GENERATED TEXT DETECTION
# ============================================================

def detect_ai_text(text):

    text = str(text)

    text_tfidf = ai_text_tfidf.transform([text])

    prediction = ai_text_model.predict(text_tfidf)[0]

    probabilities = ai_text_model.predict_proba(text_tfidf)[0]

    if prediction == 0:
        result = "HUMAN-WRITTEN"
        confidence = probabilities[0] * 100
    else:
        result = "AI-GENERATED"
        confidence = probabilities[1] * 100

    return result, confidence


# ============================================================
# DEEPFAKE IMAGE DETECTION
# ============================================================

def detect_deepfake(image_path):

    image = load_img(
        image_path,
        target_size=(224, 224)
    )

    image_array = img_to_array(image)

    image_array = np.expand_dims(
        image_array,
        axis=0
    )

    prediction_probability = deepfake_model.predict(
        image_array,
        verbose=0
    )[0][0]

    if prediction_probability >= 0.5:
        result = "REAL IMAGE"
        confidence = prediction_probability * 100
    else:
        result = "FAKE IMAGE"
        confidence = (1 - prediction_probability) * 100

    return result, confidence


# ============================================================
# UNIFIED CONTENT VERIFICATION
# ============================================================

def unified_content_verification(
    content_type,
    content,
    title=None
):

    content_type = content_type.lower().strip()

