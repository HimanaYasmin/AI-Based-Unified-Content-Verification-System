def detect_fake_news(title, text):
    """
    Detect whether a news article is Fake or Real.
    Uses the saved TF-IDF vectorizer and Logistic Regression model.
    """

    # Combine title and article text exactly like the training pipeline
    combined_text = str(title) + " " + str(text)

    # Transform using the SAVED TF-IDF vectorizer
    text_tfidf = fake_news_tfidf.transform([combined_text])

    # Get prediction
    prediction = fake_news_model.predict(text_tfidf)[0]

    # Get probability
    probabilities = fake_news_model.predict_proba(text_tfidf)[0]

    # Convert model output to human-readable label
    if prediction == 0:
        result = "FAKE NEWS"
        confidence = probabilities[0] * 100
    else:
        result = "REAL NEWS"
        confidence = probabilities[1] * 100

    return result, confidence


