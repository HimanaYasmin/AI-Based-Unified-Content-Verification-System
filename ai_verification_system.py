def unified_content_verification(content_type, content, title=None):
    """
    Unified Content Verification System.

    content_type:
        "fake_news"
        "ai_text"
        "deepfake"

    content:
        Text for fake news / AI text.
        Image file path for deepfake.

    title:
        News title (used only for fake news).
    """

    content_type = content_type.lower().strip()

    # =========================
    # Fake News Detection
    # =========================
    if content_type == "fake_news":
        if title is None:
            title = ""

        result, confidence = detect_fake_news(title, content)

        return {
            "module": "Fake News Detection",
            "result": result,
            "confidence": confidence
        }

    # =========================
    # AI Text Detection
    # =========================
    elif content_type == "ai_text":
        result, confidence = detect_ai_text(content)

        return {
            "module": "AI-Generated Text Detection",
            "result": result,
            "confidence": confidence
        }

    # =========================
    # Deepfake Detection
    # =========================
    elif content_type == "deepfake":
        result, confidence = detect_deepfake(content)

        return {
            "module": "Deepfake Image Detection",
            "result": result,
            "confidence": confidence
        }

    # =========================
    # Invalid content type
    # =========================
    else:
        raise ValueError(
            "Invalid content type. Use: "
            "'fake_news', 'ai_text', or 'deepfake'."
        )


